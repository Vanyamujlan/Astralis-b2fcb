def build_full_tarot_deck() -> tuple[TarotCard, ...]:
    """Construct the complete 78-card Rider-Waite Tarot deck."""
    cards: list[TarotCard] = []

    for card_id, name_ru, up_kw, rev_kw, up_meaning, rev_meaning, advice in _MAJOR_ARCANA_DATA:
        cards.append(
            TarotCard(
                card_id=card_id,
                name_ru=name_ru,
                arcana="major",
                suit_ru=None,
                upright_keywords=up_kw,
                reversed_keywords=rev_kw,
                upright_meaning=up_meaning,
                reversed_meaning=rev_meaning,
                advice=advice,
            )
        )

    for suit_key, suit_ru, suit_up_theme, suit_rev_theme in _SUITS:
        for rank_key, rank_ru, up_kw, rev_kw, up_text, rev_text in _RANKS:
            cards.append(
                TarotCard(
                    card_id=f"{suit_key}_{rank_key}",
                    name_ru=f"{rank_ru} {suit_ru}",
                    arcana="minor",
                    suit_ru=suit_ru,
                    upright_keywords=f"{up_kw} ({suit_up_theme})",
                    reversed_keywords=f"{rev_kw} ({suit_rev_theme})",
                    upright_meaning=f"{up_text} Сфера проявления — {suit_up_theme}.",
                    reversed_meaning=f"{rev_text} Зона внимания — {suit_rev_theme}.",
                    advice=f"Направьте внимание на {suit_up_theme} и избегайте таких крайностей, как {suit_rev_theme}.",
                )
            )

    return tuple(cards)


FULL_TAROT_DECK: tuple[TarotCard, ...] = build_full_tarot_deck()
